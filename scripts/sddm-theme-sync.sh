#!/bin/bash

# SDDM Theme Sync - Synchronizes SDDM theme with active Hyprsimple theme
# Reads colors from ~/.config/hypr/themes/hyprsimple/generated/quickshell-colors.json
# Reads wallpaper from ~/.cache/current_wallpaper
# Outputs to /usr/share/sddm/themes/hyprsimple/

set -euo pipefail

# Determine the actual user's home directory (not root's when run with sudo)
if [[ -n "${SUDO_USER:-}" ]]; then
    USER_HOME=$(getent passwd "$SUDO_USER" | cut -d: -f6)
elif [[ -n "${USER:-}" && "$USER" != "root" ]]; then
    USER_HOME=$(getent passwd "$USER" | cut -d: -f6)
else
    USER_HOME="$HOME"
fi

# Use quickshell's theme-active.json as the source of truth for active theme colors
QUICKSHELL_COLORS_FILE="${QUICKSHELL_COLORS_FILE:-$USER_HOME/.config/quickshell/theme-active.json}"
SDDM_THEME_DIR="${SDDM_THEME_DIR:-/usr/share/sddm/themes/hyprsimple}"
CACHE_DIR="${CACHE_DIR:-$USER_HOME/.cache}"
COLORS_FILE="$QUICKSHELL_COLORS_FILE"
WALLPAPER_SOURCE="$CACHE_DIR/current_wallpaper"
WALLPAPER_DEST="$SDDM_THEME_DIR/background.jpg"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log() { printf "${GREEN}[sddm-sync]${NC} %s\n" "$*"; }
warn() { printf "${YELLOW}[sddm-sync]${NC} %s\n" "$*"; }
err() { printf "${RED}[sddm-sync]${NC} %s\n" "$*" >&2; }

# Check if jq is available
if ! command -v jq >/dev/null 2>&1; then
    err "jq not found, cannot parse colors.json"
    exit 1
fi

# Check if colors file exists
if [[ ! -f "$COLORS_FILE" ]]; then
    err "Colors file not found: $COLORS_FILE"
    exit 1
fi

# Read colors from JSON
read_colors() {
    BACKGROUND=$(jq -r '.background' "$COLORS_FILE")
    SURFACE=$(jq -r '.surface' "$COLORS_FILE")
    FOREGROUND=$(jq -r '.foreground' "$COLORS_FILE")
    ACCENT=$(jq -r '.accent' "$COLORS_FILE")
    ACCENT_DIM=$(jq -r '.accent_dim' "$COLORS_FILE")
    SECONDARY=$(jq -r '.secondary' "$COLORS_FILE")
    SUCCESS=$(jq -r '.success' "$COLORS_FILE")
    WARNING=$(jq -r '.warning' "$COLORS_FILE")
    DANGER=$(jq -r '.danger' "$COLORS_FILE")
    MUTED=$(jq -r '.muted' "$COLORS_FILE")
    BORDER=$(jq -r '.border' "$COLORS_FILE")
}

# Copy wallpaper to SDDM theme directory
sync_wallpaper() {
    if [[ -f "$WALLPAPER_SOURCE" ]]; then
        cp "$WALLPAPER_SOURCE" "$WALLPAPER_DEST"
        log "Wallpaper synced to $WALLPAPER_DEST"
    else
        warn "No wallpaper source at $WALLPAPER_SOURCE"
    fi
}

# Generate theme.conf
generate_theme_conf() {
    cat > "$SDDM_THEME_DIR/theme.conf" <<EOF
[General]
background=background.jpg

[Metadata]
Name=Hyprsimple Dynamic
Version=1.0
Author=Hyprsimple Config
Description=Dynamic SDDM theme matching active Hyprsimple theme
EOF
    log "Generated theme.conf"
}

# Generate Main.qml with dynamic colors
generate_main_qml() {
    cat > "$SDDM_THEME_DIR/Main.qml" <<'QMLEOF'
/***************************************************************************
 * Hyprsimple SDDM Dynamic Theme
 * Colors and wallpaper synchronized from active Hyprsimple theme
 * DO NOT EDIT - Generated by sddm-theme-sync.sh
 ***************************************************************************/

import QtQuick 2.0
import SddmComponents 2.0

Rectangle {
    id: container
    width: 640
    height: 480

    LayoutMirroring.enabled: Qt.locale().textDirection == Qt.RightToLeft
    LayoutMirroring.childrenInherit: true

    property int sessionIndex: session.index

    TextConstants { id: textConstants }

    Connections {
        target: sddm

        function onLoginSucceeded() {
            errorMessage.color = @@ACCENT@@
            errorMessage.text = textConstants.loginSucceeded
        }
        function onLoginFailed() {
            password.text = ""
            errorMessage.color = @@DANGER@@
            errorMessage.text = textConstants.loginFailed
        }
        function onInformationMessage(message) {
            errorMessage.color = @@DANGER@@
            errorMessage.text = message
        }
    }

    // Background
    Background {
        anchors.fill: parent
        source: Qt.resolvedUrl(config.background)
        fillMode: Image.PreserveAspectCrop
        onStatusChanged: {
            var defaultBackground = Qt.resolvedUrl(config.defaultBackground)
            if (status == Image.Error && source != defaultBackground) {
                source = defaultBackground
            }
        }
    }

    // Dark overlay for better text readability
    Rectangle {
        anchors.fill: parent
        color: @@BACKGROUND@@
        opacity: 0.6
    }

    // Main login panel
    Rectangle {
        id: loginPanel
        anchors.centerIn: parent
        width: Math.max(360, mainColumn.implicitWidth + 60)
        height: mainColumn.implicitHeight + 60
        radius: 12
        color: @@SURFACE@@
        border.color: @@ACCENT@@
        border.width: 2

        Column {
            id: mainColumn
            anchors.centerIn: parent
            spacing: 16

            // Welcome text
            Text {
                id: welcomeText
                anchors.horizontalCenter: parent.horizontalCenter
                color: @@FOREGROUND@@
                text: textConstants.welcomeText.arg(sddm.hostName)
                wrapMode: Text.WordWrap
                font.pixelSize: 22
                font.weight: Font.Medium
                elide: Text.ElideRight
                horizontalAlignment: Text.AlignHCenter
            }

            // Username field
            Column {
                width: parent.width
                spacing: 6
                Text {
                    text: textConstants.userName
                    color: @@FOREGROUND@@
                    font.bold: true
                    font.pixelSize: 13
                }

                TextBox {
                    id: name
                    width: parent.width; height: 38
                    text: userModel.lastUser
                    font.pixelSize: 15
                    textColor: @@FOREGROUND@@
                    color: @@SURFACE@@
                    borderColor: @@MUTED@@
                    focusColor: @@ACCENT@@
                    hoverColor: @@ACCENT_DIM@@
                    radius: 6
                    KeyNavigation.backtab: rebootButton; KeyNavigation.tab: password

                    Keys.onPressed: function (event) {
                        if (event.key === Qt.Key_Return || event.key === Qt.Key_Enter) {
                            sddm.login(name.text, password.text, sessionIndex)
                            event.accepted = true
                        }
                    }
                }
            }

            // Password field
            Column {
                width: parent.width
                spacing: 6
                Text {
                    text: textConstants.password
                    color: @@FOREGROUND@@
                    font.bold: true
                    font.pixelSize: 13
                }

                PasswordBox {
                    id: password
                    width: parent.width; height: 38
                    font.pixelSize: 15
                    textColor: @@FOREGROUND@@
                    color: @@SURFACE@@
                    borderColor: @@MUTED@@
                    focusColor: @@ACCENT@@
                    hoverColor: @@ACCENT_DIM@@
                    radius: 6
                    KeyNavigation.backtab: name; KeyNavigation.tab: session

                    Keys.onPressed: function (event) {
                        if (event.key === Qt.Key_Return || event.key === Qt.Key_Enter) {
                            sddm.login(name.text, password.text, sessionIndex)
                            event.accepted = true
                        }
                    }
                }
            }

            // Session selector
            Column {
                width: parent.width
                spacing: 6
                Text {
                    text: textConstants.session
                    color: @@FOREGROUND@@
                    font.bold: true
                    font.pixelSize: 13
                }

                ComboBox {
                    id: session
                    width: parent.width; height: 38
                    font.pixelSize: 15
                    color: @@SURFACE@@
                    borderColor: @@MUTED@@
                    focusColor: @@ACCENT@@
                    hoverColor: @@ACCENT_DIM@@
                    textColor: @@FOREGROUND@@
                    menuColor: @@SURFACE@@
                    arrowColor: @@ACCENT@@
                    KeyNavigation.backtab: password; KeyNavigation.tab: layoutBox
                }
            }

            // Keyboard layout (only show if multiple)
            Column {
                width: parent.width
                spacing: 6
                visible: keyboard.enabled && keyboard.layouts.length > 0

                Text {
                    text: textConstants.layout
                    color: @@FOREGROUND@@
                    font.bold: true
                    font.pixelSize: 13
                }

                LayoutBox {
                    id: layoutBox
                    width: parent.width; height: 38
                    font.pixelSize: 15
                    color: @@FOREGROUND@@
                    KeyNavigation.backtab: session; KeyNavigation.tab: loginButton
                }
            }

            // Error/info message
            Text {
                id: errorMessage
                anchors.horizontalCenter: parent.horizontalCenter
                text: textConstants.prompt
                color: @@MUTED@@
                font.pixelSize: 11
                wrapMode: Text.WordWrap
            }

            // Buttons
            Row {
                spacing: 10
                anchors.horizontalCenter: parent.horizontalCenter
                property int btnWidth: Math.max(loginButton.implicitWidth,
                                                shutdownButton.implicitWidth,
                                                rebootButton.implicitWidth, 100) + 16

                Button {
                    id: loginButton
                    text: textConstants.login
                    width: parent.btnWidth
                    height: 40
                    font.pixelSize: 14
                    font.bold: true
                    textColor: @@FOREGROUND@@
                    color: @@ACCENT@@
                    activeColor: @@ACCENT_DIM@@
                    pressedColor: @@SURFACE@@
                    borderColor: @@ACCENT@@
                    onClicked: sddm.login(name.text, password.text, sessionIndex)
                    KeyNavigation.backtab: layoutBox; KeyNavigation.tab: shutdownButton
                }

                Button {
                    id: shutdownButton
                    text: textConstants.shutdown
                    width: parent.btnWidth
                    height: 40
                    font.pixelSize: 14
                    textColor: @@FOREGROUND@@
                    color: @@SURFACE@@
                    activeColor: "#2E3A59"
                    pressedColor: "#2E3A59"
                    borderColor: @@DANGER@@
                    onClicked: sddm.powerOff()
                    KeyNavigation.backtab: loginButton; KeyNavigation.tab: rebootButton
                }

                Button {
                    id: rebootButton
                    text: textConstants.reboot
                    width: parent.btnWidth
                    height: 40
                    font.pixelSize: 14
                    textColor: @@FOREGROUND@@
                    color: @@SURFACE@@
                    activeColor: "#2E3A59"
                    pressedColor: "#2E3A59"
                    borderColor: @@WARNING@@
                    onClicked: sddm.reboot()
                    KeyNavigation.backtab: shutdownButton; KeyNavigation.tab: name
                }
            }
        }
    }

    // Clock at top-right
    Clock {
        id: clock
        anchors.top: parent.top
        anchors.right: parent.right
        anchors.margins: 24
        color: @@FOREGROUND@@
        timeFont.family: "JetBrainsMono Nerd Font Mono"
        timeFont.pixelSize: 28
        dateFont.family: "JetBrainsMono Nerd Font Mono"
        dateFont.pixelSize: 12
    }

    Component.onCompleted: {
        if (name.text == "")
            name.focus = true
        else
            password.focus = true
    }
}
QMLEOF

    # Now substitute the color placeholders with actual values (quoted for QML)
    # Use @@PLACEHOLDER@@ format to avoid any partial matches
    sed -i \
        -e "s/@@BACKGROUND@@/\"${BACKGROUND}\"/g" \
        -e "s/@@SURFACE@@/\"${SURFACE}\"/g" \
        -e "s/@@FOREGROUND@@/\"${FOREGROUND}\"/g" \
        -e "s/@@ACCENT@@/\"${ACCENT}\"/g" \
        -e "s/@@ACCENT_DIM@@/\"${ACCENT_DIM}\"/g" \
        -e "s/@@SECONDARY@@/\"${SECONDARY}\"/g" \
        -e "s/@@SUCCESS@@/\"${SUCCESS}\"/g" \
        -e "s/@@WARNING@@/\"${WARNING}\"/g" \
        -e "s/@@DANGER@@/\"${DANGER}\"/g" \
        -e "s/@@MUTED@@/\"${MUTED}\"/g" \
        -e "s/@@BORDER@@/\"${BORDER}\"/g" \
        "$SDDM_THEME_DIR/Main.qml"

    log "Generated Main.qml with dynamic colors"
}

# Main execution
main() {
    log "Starting SDDM theme sync..."
    log "User home: $USER_HOME"

    read_colors
    log "Colors loaded from $COLORS_FILE"

    sync_wallpaper

    generate_theme_conf

    generate_main_qml

    log "SDDM theme sync complete"
}

main "$@"